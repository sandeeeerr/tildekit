// tilde build: the always-on rules for Codex and Cursor, made from the home's AGENTS.md and this machine's device file.
// Claude needs no copy: it imports those two files directly.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { CONF, HOME, TILDE, readText } from "./config.ts";

const MAX_BYTES = 24576; // ponytail: Codex reads at most 32 KiB, together with the project's AGENTS.md
export const CODEX = join(HOME, ".codex/AGENTS.md");
export const CURSOR = join(HOME, ".cursor/rules/tilde.mdc");
const CURSOR_HEADER = "---\ndescription: Tilde, always-on rules\nalwaysApply: true\n---\n\n";

/** The name this machine got from tilde setup; its file in devices/ holds what is only true here. */
export const device = () => readText(join(CONF, "device"))?.trim() ?? "";

/** How a copy made by tilde build starts; tilde uninstall removes only files that carry it. */
export const GENERATED = "<!-- Generated by tilde build from ~/tilde.";

/** The rules as Codex reads them. Throws when the home has no AGENTS.md. */
export function codexRules(): string {
  const header = `${GENERATED} Edit there, not here. -->\n\n`;
  const deviceRules = readText(join(TILDE, "devices", `${device()}.md`));
  const agents = readFileSync(join(TILDE, "AGENTS.md"), "utf8");
  return header + agents + (deviceRules === undefined ? "" : `\n${deviceRules}`);
}

/** The same rules as an always-on Cursor rule. */
export const cursorRules = () => CURSOR_HEADER + codexRules();

export function build(): void {
  const text = codexRules();
  const size = Buffer.byteLength(text);
  if (size > MAX_BYTES) throw new Error(`tilde build: AGENTS.md + device file is ${size} bytes, max ${MAX_BYTES}`);
  for (const [file, content] of [[CODEX, text], [CURSOR, CURSOR_HEADER + text]]) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
